"""Generates the Namazim launcher icon: the "hilal saat" crescent as dantel (lace).

The crescent is the lune between disc (54,54) r30 and disc (64,46) r26 — the shape the owner picked.
Its body is a fine gold lattice (thin crossed lines clipped to the lune) inside a thin gold rim, the way
the reference "Vakit" icon does its lace: dark inside, gold threads, nothing filled.
Five dots and the hand stay: the crescent is a clock face pointing at the next vakit.

Writes app/src/main/res/drawable/ic_logo.xml and design/icon-preview.html, plus PNG proofs.
Run: python design/logo-gen.py
"""
import math
from PIL import Image, ImageDraw

O = (54.0, 54.0)
R = 30.0
C = (64.0, 46.0)
r = 26.0
GOLD = (232, 190, 116)
INK = (243, 238, 227)
BG = (14, 26, 48)

# The lune, as in the original hand-made icon (outer arc, then the inner arc back).
LUNE = "M49.65,24.31 A30,30 0 1,0 82.01,64.75 A26,26 0 1,1 49.65,24.31 Z"

DOTS = [(54, 33), (64.5, 35.8), (72.2, 43.5), (75, 54), (72.2, 64.5)]


def lattice(spacing=4.0):
    """Two families of 45-degree lines across the whole icon; the clip path keeps them inside."""
    out = []
    c = -84.0
    while c <= 84.0:
        out.append(f"M20,{20 + c:.1f} L88,{88 + c:.1f}")   # y = x + c
        out.append(f"M20,{c - 20:.1f} L88,{c - 88:.1f}")   # y = -x + c
        c += spacing
    return " ".join(out)


def polygon_lattice():
    """Girih-ish star lattice: verticals plus two diagonal families, thin enough to read as lace."""
    return lattice(4.0)


def circle_path(x, y, rad):
    return (f"M{x - rad:.2f},{y:.2f} a{rad:.2f},{rad:.2f} 0 1,0 {2 * rad:.2f},0 "
            f"a{rad:.2f},{rad:.2f} 0 1,0 {-2 * rad:.2f},0 Z")


def emit_xml(path):
    dots = " ".join(circle_path(x, y, 2.4) for (x, y) in DOTS)
    xml = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- "Hilal saat" as dantel: a thin gold rim around the crescent, its body a fine gold lattice
     clipped to the lune, plus the clock face (five vakit dots, hand to the next one).
     Generated by design/logo-gen.py — edit that, not this file. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <group>
        <clip-path android:pathData="{LUNE}" />
        <path android:strokeColor="#E8BE74" android:strokeWidth="0.5"
            android:pathData="{polygon_lattice()}" />
    </group>
    <path android:strokeColor="#E8BE74" android:strokeWidth="1.3" android:strokeLineJoin="round"
        android:pathData="{LUNE}" />
    <path android:fillColor="#E8BE74" android:fillAlpha="0.45" android:pathData="{dots}" />
    <path android:strokeColor="#F3EEE3" android:strokeWidth="3.4" android:strokeLineCap="round"
        android:pathData="M54,54 L66,47" />
    <path android:fillColor="#F3EEE3"
        android:pathData="M50.6,54 a3.4,3.4 0 1,0 6.8,0 a3.4,3.4 0 1,0 -6.8,0" />
</vector>
'''
    with open(path, "w", encoding="utf-8") as f:
        f.write(xml)


def emit_html(path):
    dots = "".join(f'<circle cx="{x}" cy="{y}" r="2.4" fill="#E8BE74" fill-opacity="0.45"/>' for (x, y) in DOTS)
    svg = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" width="100%" height="100%">
  <circle cx="54" cy="54" r="54" fill="#0E1A30"/>
  <defs><clipPath id="lune"><path d="{LUNE}"/></clipPath></defs>
  <g clip-path="url(#lune)">
    <path d="{polygon_lattice()}" stroke="#E8BE74" stroke-width="0.5" fill="none"/>
  </g>
  <path d="{LUNE}" stroke="#E8BE74" stroke-width="1.3" fill="none"/>
  {dots}
  <path d="M54,54 L66,47" stroke="#F3EEE3" stroke-width="3.4" stroke-linecap="round"/>
  <circle cx="54" cy="54" r="3.4" fill="#F3EEE3"/>
</svg>'''
    sizes = (216, 108, 56, 33)
    html = ('<!doctype html><meta charset="utf-8"><style>body{margin:0;background:#1a202c;display:flex;'
            'gap:28px;align-items:center;padding:28px}div{border-radius:50%;overflow:hidden;'
            'box-shadow:0 6px 20px #0008}</style>'
            + ''.join(f'<div style="width:{s}px;height:{s}px">{svg}</div>' for s in sizes))
    with open(path, "w", encoding="utf-8") as f:
        f.write(html)


def render(px, scale=8):
    """Pillow proof: gold rim + lattice masked to the lune, on the icon background."""
    img = Image.new("RGBA", (108 * scale, 108 * scale), BG + (255,))
    mask = Image.new("L", (108 * scale, 108 * scale), 0)
    md = ImageDraw.Draw(mask)
    md.ellipse(((O[0] - R) * scale, (O[1] - R) * scale, (O[0] + R) * scale, (O[1] + R) * scale), fill=255)
    md.ellipse(((C[0] - r) * scale, (C[1] - r) * scale, (C[0] + r) * scale, (C[1] + r) * scale), fill=0)

    thread = Image.new("RGBA", img.size, (0, 0, 0, 0))
    td = ImageDraw.Draw(thread)
    c = -84.0
    while c <= 84.0:
        td.line(((20) * scale, (20 + c) * scale, 88 * scale, (88 + c) * scale), fill=GOLD + (255,), width=max(1, int(0.5 * scale)))
        td.line(((20) * scale, (c - 20) * scale, 88 * scale, (c - 88) * scale), fill=GOLD + (255,), width=max(1, int(0.5 * scale)))
        c += 4.0
    img = Image.composite(thread, img, mask)
    d = ImageDraw.Draw(img)
    # rim
    d.ellipse(((O[0] - R) * scale, (O[1] - R) * scale, (O[0] + R) * scale, (O[1] + R) * scale), outline=GOLD + (255,), width=int(1.3 * scale))
    d.ellipse(((C[0] - r) * scale, (C[1] - r) * scale, (C[0] + r) * scale, (C[1] + r) * scale), fill=BG + (255,))
    d.ellipse(((C[0] - r) * scale, (C[1] - r) * scale, (C[0] + r) * scale, (C[1] + r) * scale), outline=GOLD + (255,), width=int(1.3 * scale))
    for (x, y) in DOTS:
        d.ellipse(((x - 2.4) * scale, (y - 2.4) * scale, (x + 2.4) * scale, (y + 2.4) * scale), fill=GOLD + (115,))
    d.line((54 * scale, 54 * scale, 66 * scale, 47 * scale), fill=INK + (255,), width=int(3.4 * scale))
    d.ellipse(((54 - 3.4) * scale, (54 - 3.4) * scale, (54 + 3.4) * scale, (54 + 3.4) * scale), fill=INK + (255,))
    img.resize((px, px), Image.LANCZOS).save(f"vakit-ekran/logo-lace-{px}.png")


if __name__ == "__main__":
    emit_xml("app/src/main/res/drawable/ic_logo.xml")
    emit_html("design/icon-preview.html")
    render(216)
    render(56)
    print("ic_logo.xml + icon-preview.html written")

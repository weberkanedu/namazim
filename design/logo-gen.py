"""Generates the Namazim launcher icon: "Beş vakit gülü" (design B in design/logo-secenekler.html).

A rose seen from above, drawn like the Ottoman gül motif: five overlapping outer petals (one per vakit),
five smaller petals turned between them, a spiral bud, inside a faint gold ring. One outer petal is
tinted: the next vakit, the job the old clock hand did.

Launcher look since 2026-11-08 (design L1 in design/logo-parlak-secenekler.html): the old navy icon got lost among
bright launcher icons, so the background is now gold (res/drawable/ic_bg_gold.xml) and the rose is navy-filled with
light gold edges, a bit larger, no ring and no tinted petal. The themed (mono) layer is unchanged.

Writes:
  app/src/main/res/drawable/ic_logo.xml       adaptive-icon foreground (petals filled with the background
                                              colour so each one covers the one before it)
  app/src/main/res/drawable/ic_logo_mono.xml  themed-icon layer: lines only, since Android paints every
                                              opaque pixel of it in one colour
  design/icon-preview.html                    the icon at launcher sizes
Run: python design/logo-gen.py
"""
import math

GOLD = "#E8BE74"
BG = "#0E1A30"            # @color/icon_bg
CX, CY, R = 54.0, 54.0, 27.0
LIT = 1                   # the tinted petal (top right), mono/old look only
NAVY = "#14213D"          # L1 petal fill
EDGE = "#F6D899"          # L1 petal edge
GOLDBG = ("#FFE3A3", "#E5B565", "#B07A28")   # ic_bg_gold.xml, top-left to bottom-right
# Cuma icon C2 "Zümrüt" (design/design-system/cuma-secenekler.html): gold rose with cream edges on emerald, faint gold rays
EMERALD = ("#2E8A6C", "#1C6650", "#0F3D30")
CUMA_PETAL = "#E3B35E"
CUMA_EDGE = "#FFF0C8"


def P(r, a):
    t = math.radians(a - 90)
    return CX + r * math.cos(t), CY + r * math.sin(t)


def f(p):
    return f"{p[0]:.2f},{p[1]:.2f}"


def petal(r0, r1, a0, a1):
    """Open petal edge from (r0,a0) out to its rounded tip and back to (r0,a1)."""
    w = a1 - a0
    return (f"M{f(P(r0, a0))} C{f(P(r1 * 1.02, a0 - w * .08))} {f(P(r1 * 1.16, a0 + w * .34))} {f(P(r1, a0 + w * .5))} "
            f"C{f(P(r1 * 1.16, a1 - w * .34))} {f(P(r1 * 1.02, a1 + w * .08))} {f(P(r0, a1))}")


def outer():
    return [petal(R * .34, R, i * 72 - 40, i * 72 + 40) for i in range(5)]


def inner():
    return [petal(R * .16, R * .6, i * 72 + 36 - 38, i * 72 + 36 + 38) for i in range(5)]


def bud():
    pts = []
    for k in range(61):
        th = k / 60 * math.pi * 3.2
        r = R * .24 * (1 - k / 68)
        pts.append((CX + r * math.cos(th), CY + r * math.sin(th)))
    return "M" + " L".join(f(p) for p in pts)


RING = f"M{CX - 31.5:.2f},{CY:.2f} a31.5,31.5 0 1,0 63,0 a31.5,31.5 0 1,0 -63,0"
HEAD = '''<?xml version="1.0" encoding="utf-8"?>
<!-- {what}
     Generated by design/logo-gen.py — edit that, not this file. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
'''


def emit_xml(path, mono):
    out = [HEAD.format(what="\"Beş vakit gülü\": " + ("themed-icon layer, lines only." if mono else
                                                      "L1: navy petals with light gold edges on the gold background, a spiral bud."))]
    if mono:
        out.append(f'    <path android:strokeColor="{GOLD}" android:strokeWidth="0.6" android:strokeAlpha="0.45" android:pathData="{RING}" />\n')
        for d in outer():
            out.append(f'    <path android:strokeColor="{GOLD}" android:strokeWidth="1.5" android:strokeLineJoin="round" '
                       f'android:strokeLineCap="round" android:pathData="{d}" />\n')
        for d in inner():
            out.append(f'    <path android:strokeColor="{GOLD}" android:strokeWidth="1.3" android:strokeLineCap="round" android:pathData="{d}" />\n')
        out.append(f'    <path android:strokeColor="{GOLD}" android:strokeWidth="1.35" android:strokeLineCap="round" android:pathData="{bud()}" />\n')
    else:
        # a little larger than the mono layer; still inside the launcher's visible 72dp
        out.append(f'    <group android:scaleX="1.06" android:scaleY="1.06" android:pivotX="{CX}" android:pivotY="{CY}">\n')
        for d in outer():
            out.append(f'    <path android:fillColor="{NAVY}" android:pathData="{d} Z" />\n')
            out.append(f'    <path android:strokeColor="{EDGE}" android:strokeWidth="1.7" android:strokeLineJoin="round" '
                       f'android:strokeLineCap="round" android:pathData="{d}" />\n')
        for d in inner():
            out.append(f'    <path android:strokeColor="{GOLD}" android:strokeWidth="1.5" android:strokeLineCap="round" android:pathData="{d}" />\n')
        out.append(f'    <path android:strokeColor="{GOLD}" android:strokeWidth="1.6" android:strokeLineCap="round" android:pathData="{bud()}" />\n')
        out.append('    </group>\n')
    out.append('</vector>\n')
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("".join(out))


def emit_bg(path):
    a, b, c = GOLDBG
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Launcher icon background, design L1. Generated by design/logo-gen.py — edit that, not this file. -->
<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle">
    <gradient android:angle="315" android:startColor="{a}" android:centerColor="{b}" android:endColor="{c}" />
</shape>
''')


def rays(n=16, r0=30, r1=56, w=3, rot=0):
    out = []
    for i in range(n):
        t = i / n * 360 + rot
        out.append(f"M{f(P(r0, t - w))} L{f(P(r1, t))} L{f(P(r0, t + w))} Z")
    return out


def star(r):
    # eight-pointed star (two squares, one turned 45°), as in the Selçuklu / Osmanlı tiles
    d = ""
    for k in range(2):
        pts = [f(P(r, i * 90 + k * 45)) for i in range(4)]
        d += "M" + " L".join(pts) + " Z "
    return d.strip()


def rose_xml(fill, edge, line, sw=1.5):
    out = [f'    <group android:scaleX="1.06" android:scaleY="1.06" android:pivotX="{CX}" android:pivotY="{CY}">\n']
    for d in outer():
        out.append(f'    <path android:fillColor="{fill}" android:pathData="{d} Z" />\n')
        out.append(f'    <path android:strokeColor="{edge}" android:strokeWidth="{sw}" android:strokeLineJoin="round" '
                   f'android:strokeLineCap="round" android:pathData="{d}" />\n')
    for d in inner():
        out.append(f'    <path android:strokeColor="{line}" android:strokeWidth="{sw * .86:.2f}" android:strokeLineCap="round" android:pathData="{d}" />\n')
    out.append(f'    <path android:strokeColor="{line}" android:strokeWidth="{sw * .9:.2f}" android:strokeLineCap="round" android:pathData="{bud()}" />\n')
    out.append('    </group>\n')
    return out


def ray_xml(color, alpha, **kw):
    return [f'    <path android:fillColor="{color}" android:fillAlpha="{alpha if i % 2 == 0 else alpha / 2:.3f}" android:pathData="{d}" />\n'
            for i, d in enumerate(rays(**kw))]


def glow_xml(color, rings=((44, .05), (36, .06), (28, .07))):
    # a soft halo behind the rose; vector drawables have no blur, so a few faint discs
    return [f'    <path android:fillColor="{color}" android:fillAlpha="{al}" android:pathData="M{CX - r},{CY} a{r},{r} 0 1,0 {2 * r},0 a{r},{r} 0 1,0 {-2 * r},0" />\n'
            for r, al in rings]


def sunset_xml():
    # İkindi "Gün batımı": rays rising from the sun below the bottom edge
    out = []
    for i in range(9):
        t = math.radians(-80 + i * 20)
        x0, y0 = 54 + 34 * math.sin(t), 110 - 34 * math.cos(t)
        x1, y1 = 54 + 70 * math.sin(t), 110 - 70 * math.cos(t)
        out.append(f'    <path android:strokeColor="#FFE3A3" android:strokeAlpha="0.35" android:strokeWidth="1.2" android:pathData="M{x0:.2f},{y0:.2f} L{x1:.2f},{y1:.2f}" />\n')
    return out


def star_xml():
    st = star(45)
    return [f'    <path android:fillColor="{GOLD}" android:fillAlpha="0.15" android:strokeColor="{GOLD}" android:strokeAlpha="0.92" android:strokeWidth="1.4" android:strokeLineJoin="round" android:pathData="{st}" />\n',
            f'    <path android:strokeColor="{GOLD}" android:strokeAlpha="0.5" android:strokeWidth="0.7" android:strokeLineJoin="round" android:pathData="{star(39)}" />\n',
            f'    <path android:strokeColor="#FFE3A3" android:strokeAlpha="0.7" android:strokeWidth="1" android:strokeLineJoin="round" android:pathData="{star(42)}" />\n']


# The icon family (design/design-system/vakit-ikon-secenekler.html, 2026-11-10): name -> (what, background, foreground).
# Background = (angle, start, center, end) of a linear gradient, optionally + a radial glow layer for the widget art.
GOLD_ROSE = ("#E8BE74", "#FFF4D6", "#FFF4D6")
NIGHT = (315, "#1B2B52", "#101B36", "#070D1D")
ICONS = {
    "zumrut": ("Zümrüt, the everyday launcher icon and Akşam's widget art: gold rose with cream edges and faint gold rays on emerald.",
               (315,) + EMERALD, lambda: ray_xml(GOLD, .22) + rose_xml(CUMA_PETAL, CUMA_EDGE, CUMA_EDGE)),
    "cuma": ("Cuma: night blue, long thin rays between the points of a gold eight-pointed star (the star is Cuma's alone), gold rose.",
             NIGHT, lambda: glow_xml("#FFE3A3") + ray_xml("#FFF4D6", .32, n=32, r0=30, r1=60, w=1.3, rot=5.625) + star_xml() + rose_xml(*GOLD_ROSE)),
    "imsak": ("İmsak \"Sedef\": pearl background, emerald petals with gold edges.",
              (315, "#FFFDF6", "#F2EADB", "#D9CCB4"), lambda: ray_xml("#E5B565", .28) + rose_xml("#1F7259", "#C99A4A", "#F6E3B8")),
    "ogle": ("Öğle \"Altın zümrüt\": gold background, emerald petals.",
             (315,) + GOLDBG, lambda: ray_xml("#FFFFFF", .35) + rose_xml("#1C6650", "#0F3D30", "#FFF0C8")),
    "ikindi": ("İkindi \"Gün batımı\": navy to red to orange, the setting sun's glow and rays at the bottom, gold rose.",
               (270, "#2A2F63", "#8E3B4A", "#E0874F"), lambda: sunset_xml() + rose_xml(*GOLD_ROSE)),
    "yatsi": ("Yatsı \"Gece nuru\": night blue, a halo and gold rays, gold rose.",
              NIGHT, lambda: glow_xml("#FFE3A3") + ray_xml("#FFE3A3", .35, n=24, r0=28, r1=58, w=2.4) + rose_xml(*GOLD_ROSE)),
}
GEN = "Generated by design/logo-gen.py — edit that, not this file."


def emit_family(drawable):
    for name, (what, bg, fg) in ICONS.items():
        with open(f"{drawable}/ic_logo_{name}.xml", "w", encoding="utf-8") as fh:
            fh.write(HEAD.format(what=f'"Beş vakit gülü", {what}') + "".join(fg()) + "</vector>\n")
        ang, a, b, c = bg
        with open(f"{drawable}/ic_bg_{name}.xml", "w", encoding="utf-8") as fh:
            fh.write(f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Background of ic_logo_{name}. {GEN} -->
<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle">
    <gradient android:angle="{ang}" android:startColor="{a}" android:centerColor="{b}" android:endColor="{c}" />
</shape>
''')
        # the 1×1 widget draws background + art as one picture (VakitWidgets / NamazimWidget.art)
        glow = ('    <item>\n        <shape android:shape="rectangle">\n            <gradient android:type="radial" android:centerX="0.5" android:centerY="1.0" '
                'android:gradientRadius="60dp" android:startColor="#F2FFE3A3" android:centerColor="#8CF2A65A" android:endColor="#00F2A65A" />\n'
                '        </shape>\n    </item>\n') if name == "ikindi" else ""
        with open(f"{drawable}/wg_vakit_{name}.xml", "w", encoding="utf-8") as fh:
            fh.write(f'''<?xml version="1.0" encoding="utf-8"?>
<!-- The 1×1 widget's art for {name}: background and rose in one. {GEN} -->
<layer-list xmlns:android="http://schemas.android.com/apk/res/android">
    <item android:drawable="@drawable/ic_bg_{name}" />
{glow}    <item android:drawable="@drawable/ic_logo_{name}" />
</layer-list>
''')


def emit_html(path):
    parts = []
    for d in outer():
        parts.append(f'<path d="{d} Z" fill="{NAVY}"/>')
        parts.append(f'<path d="{d}" stroke="{EDGE}" stroke-width="1.7" fill="none" stroke-linejoin="round" stroke-linecap="round"/>')
    parts += [f'<path d="{d}" stroke="{GOLD}" stroke-width="1.5" fill="none" stroke-linecap="round"/>' for d in inner()]
    parts.append(f'<path d="{bud()}" stroke="{GOLD}" stroke-width="1.6" fill="none" stroke-linecap="round"/>')
    a, b, c = GOLDBG
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="18 18 72 72" width="100%" height="100%">'
           f'<defs><linearGradient id="bg" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="{a}"/>'
           f'<stop offset=".5" stop-color="{b}"/><stop offset="1" stop-color="{c}"/></linearGradient></defs>'
           f'<rect width="108" height="108" fill="url(#bg)"/><g transform="translate(54 54) scale(1.06) translate(-54 -54)">{"".join(parts)}</g></svg>')
    sizes = (216, 108, 56, 33)
    html = ('<!doctype html><meta charset="utf-8"><title>Namazım ikonu</title><style>body{margin:0;background:#1a202c;display:flex;'
            'gap:28px;align-items:center;padding:28px}div{border-radius:50%;overflow:hidden;'
            'box-shadow:0 6px 20px #0008}</style>'
            + ''.join(f'<div style="width:{s}px;height:{s}px">{svg}</div>' for s in sizes))
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(html)


if __name__ == "__main__":
    emit_xml("app/src/main/res/drawable/ic_logo.xml", mono=False)
    emit_xml("app/src/main/res/drawable/ic_logo_mono.xml", mono=True)
    emit_bg("app/src/main/res/drawable/ic_bg_gold.xml")
    emit_family("app/src/main/res/drawable")
    emit_html("design/icon-preview.html")
    print("ic_logo.xml + ic_logo_mono.xml + ic_bg_gold.xml + the vakit/Cuma family (ic_logo_*, ic_bg_*, wg_vakit_*) + icon-preview.html written")
